# --- списки и статистика ---
def empty_list() -> str:
    return pick("🐹 Щёки пустые, всё разложено! Неси ещё добычу.",
                "🌰 Ничего не лежит без дела. Горжусь нами.",
                "🐹 Пусто. Непривычно… Кидай что-нибудь!")


def list_head(n: int) -> str:
    if n >= 10:
        return f"🐹 Щёки трещат! Ждут своего часа: {n}"
    if n >= 4:
        return f"🌰 В щеках набралось: {n}"
    return f"🐹 Ждут установки: {n}"


def rank(total: int) -> str:
    for threshold, title in ((50, "👑 Легенда норки"), (30, "🏰 Хомяк-магнат"), (15, "📦 Главный кладовщик"),
                             (5, "🌰 Запасливый"), (0, "🐣 Хомячок-новичок")):
        if total >= threshold:
            return title
    return ""


# --- напоминания ---
def nudge(title: str, n: int, days: int) -> str:
    if days >= 21:
        return pick(f"🐹 Слушай… «{title}» (#{n}) лежит у меня уже {days} дн. Оно там прорастает, честно. Ставим или выплёвываем?",
                    f"😤 «{title}» (#{n}) — {days} дн. в щеке. Я хомяк терпеливый, но не настолько.")
    if days >= 7:
        return pick(f"🐹 Нашёл в кладовке «{title}» (#{n}) — тащили {days} дн. назад. Зачем-то же тащили?",
                    f"🌰 Помнишь «{title}» (#{n})? Неделю+ лежит. Давай пристроим.")
    return pick(f"🐹 Напоминаю про «{title}» (#{n}). Свеженькое, ещё пахнет новым.",
                f"🌰 Кстати, «{title}» (#{n}) ждёт. Пара минут — и оно в деле.")


def digest_head(n: int) -> str:
    return pick(f"🐹 Недельная ревизия кладовой! Без дела лежит: {n}",
                f"📋 Перебрал запасы. Не установлено: {n}. Непорядок!",
                f"🌰 Воскресная… ну или какая там сегодня… ревизия: {n} штук ждут")


